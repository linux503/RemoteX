const dict = { en, zh };

export type MessageKey = keyof typeof en;

export function resolveLocale(setting: string): Locale {
  if (setting === "zh" || setting.startsWith("zh")) return "zh";
  if (setting === "en" || setting.startsWith("en")) return "en";
  const nav = typeof navigator !== "undefined" ? navigator.language : "en";
  return nav.toLowerCase().startsWith("zh") ? "zh" : "en";
}

export function t(locale: Locale, key: MessageKey): string {
  return dict[locale][key];
}

export function translateError(locale: Locale, message: string): string {
  if (message.includes("9-digit") || message.includes("9 位")) return t(locale, "invalidId");
  if (message.toLowerCase().includes("cannot connect") || message.includes("不能连接")) {
    return t(locale, "cannotConnectSelf");
  }
  return message;
}
